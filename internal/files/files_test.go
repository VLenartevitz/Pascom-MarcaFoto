func TestScanFolder(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "a.jpg"), minimalJPEG)
	writeFile(t, filepath.Join(dir, "sub", "b.png"), minimalPNG)
	writeFile(t, filepath.Join(dir, "nota.txt"), []byte("texto"))
	writeFile(t, filepath.Join(dir, "falsa.jpg"), []byte("não é imagem"))
	res, err := ScanFolder(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Files) != 2 {
		t.Errorf("esperado 2 arquivos, obtido %d (%v)", len(res.Files), res.Files)
	}
	if res.Ignored != 1 {
		t.Errorf("esperado 1 ignorado, obtido %d", res.Ignored)
	}
	if res.Invalid != 1 {
		t.Errorf("esperado 1 inválido, obtido %d", res.Invalid)
	}
}

